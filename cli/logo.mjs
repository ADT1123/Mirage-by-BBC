// Returns 5 lines of block art, or null if the name would be wider than `max` columns.
export function banner(name, max = 80) {
  const chars = [...String(name).toUpperCase()].map((c) => FONT[c]).filter(Boolean);
  if (!chars.length) return null;
  const rows = [0, 1, 2, 3, 4].map((r) => chars.map((g) => g[r]).join('.').replace(/#/g, '█').replace(/\./g, ' '));
  return rows[0].length <= max ? rows : null;
}
