// Builds src/renderer/js/lucide.js from the Lucide icon set (ISC license, lucide.dev):
//   npm run icons
// Only the icons Mirage uses are copied, keyed by the names the app already uses.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'node_modules', 'lucide-static', 'icons');

// our name -> Lucide name
const MAP = {
  sun: 'sun', sun2: 'sun', moon: 'moon', cloud: 'cloud', partly: 'cloud-sun', rain: 'cloud-rain', snow: 'cloud-snow',
  storm: 'cloud-lightning', fog: 'cloud-fog', wifi: 'wifi', plus: 'plus', x: 'x', check: 'check', palette: 'palette',
  grid: 'layout-grid', sliders: 'sliders-horizontal', undo: 'undo-2', reset: 'rotate-ccw', image: 'image', clock: 'clock',
  commits: 'git-commit-horizontal', feed: 'git-branch', note: 'sticky-note', todo: 'list-checks', weather: 'cloud-sun',
  year: 'calendar-range', system: 'cpu', calendar: 'calendar', countdown: 'hourglass', quote: 'quote', menubar: 'panel-top',
  keyboard: 'keyboard', search: 'search', bluetooth: 'bluetooth', taskbar: 'panel-bottom', volume: 'volume-2', mute: 'volume-x',
  camera: 'camera', lock: 'lock', gear: 'settings', pencil: 'square-pen', trash: 'trash-2', power: 'power', refresh: 'refresh-cw',
  folder: 'folder', file: 'copy', globe: 'globe', calc: 'calculator', app: 'app-window', dock: 'dock', chevron: 'chevron-right',
  send: 'arrow-up', lyrics: 'mic-vocal', bolt: 'zap', leaf: 'leaf', flower: 'flower-2', stocks: 'trending-up', music: 'music',
  share: 'share', sparkle: 'sparkle', assistant: 'sparkle', stack: 'layers',
};

const out = {};
for (const [ours, lucide] of Object.entries(MAP)) {
  const svg = fs.readFileSync(path.join(SRC, `${lucide}.svg`), 'utf8');
  out[ours] = svg
    .replace(/<!--.*?-->/gs, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/ \/>/g, '/>');
}

const file = path.join(ROOT, 'src', 'renderer', 'js', 'lucide.js');
fs.writeFileSync(
  file,
  `// Generated by scripts/icons.cjs from Lucide (https://lucide.dev), ISC license. Do not edit.\n\nexport const LUCIDE = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`wrote ${Object.keys(out).length} icons to ${path.relative(ROOT, file)}`);
