const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('wall', {
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (cfg) => ipcRenderer.invoke('config:set', cfg),
  onConfig: (fn) => ipcRenderer.on('config:changed', (_e, cfg) => fn(cfg)),
  info: () => ipcRenderer.invoke('app:info'),
  preset: (theme) => ipcRenderer.invoke('app:preset', theme),
  make: (type, x, y, extra) => ipcRenderer.invoke('app:make', type, x, y, extra),
  git: (force) => ipcRenderer.invoke('data:git', force),
  weather: (force) => ipcRenderer.invoke('data:weather', force),
  system: () => ipcRenderer.invoke('data:system'),
  quote: () => ipcRenderer.invoke('data:quote'),
  verse: () => ipcRenderer.invoke('data:verse'),
  art: () => ipcRenderer.invoke('data:art'),
  geocode: (name) => ipcRenderer.invoke('data:geocode', name),
  forecast: () => ipcRenderer.invoke('data:forecast'),
  pickImage: () => ipcRenderer.invoke('dialog:image'),
  closeEditor: () => ipcRenderer.invoke('editor:close'),
  fileUrl: (p) => ipcRenderer.invoke('app:file-url', p),
  popup: (view, data) => ipcRenderer.invoke('popup:open', view, data),
  closePopup: () => ipcRenderer.invoke('popup:close'),
  popupResize: (w, h) => ipcRenderer.invoke('popup:resize', w, h),
  sysState: () => ipcRenderer.invoke('sys:state'),
  sysSet: (key, value) => ipcRenderer.invoke('sys:set', key, value),
  action: (name, arg) => ipcRenderer.invoke('sys:action', name, arg),
  dockApps: () => ipcRenderer.invoke('dock:apps'),
  spotSearch: (q) => ipcRenderer.invoke('spot:search', q),
  spotIcons: (items) => ipcRenderer.invoke('spot:icons', items),
  spotOpen: (item, reveal) => ipcRenderer.invoke('spot:open', item, reveal),
  spotHide: () => ipcRenderer.invoke('spot:hide'),
  spotResize: (h) => ipcRenderer.invoke('spot:resize', h),
  onSpotlightShow: (fn) => ipcRenderer.on('spotlight:show', () => fn()),
  onLiveOpen: (fn) => ipcRenderer.on('live:open', (_e, id) => fn(id)),
  popupReady: () => ipcRenderer.invoke('popup:ready'),
  onPopupShow: (fn) => ipcRenderer.on('popup:show', (_e, d) => fn(d)),
  onPopupHidden: (fn) => ipcRenderer.on('popup:hidden', () => fn()),
  onSysUpdate: (fn) => ipcRenderer.on('sys:update', (_e, s) => fn(s)),
  media: () => ipcRenderer.invoke('media:get'),
  mediaCmd: (cmd, arg) => ipcRenderer.invoke('media:cmd', cmd, arg),
  onMedia: (fn) => ipcRenderer.on('media:state', (_e, s) => fn(s)),
  openPlayer: () => ipcRenderer.invoke('player:open'),
  closePlayer: () => ipcRenderer.invoke('player:close'),
  mediaHistory: () => ipcRenderer.invoke('media:history'),
  onMediaHistory: (fn) => ipcRenderer.on('media:history', (_e, h) => fn(h)),
  aiAsk: (q) => ipcRenderer.invoke('ai:ask', q),
  wrapped: () => ipcRenderer.invoke('wrapped:data'),
  saveWrapped: (rect) => ipcRenderer.invoke('wrapped:save', rect),
  onPlayerShow: (fn) => ipcRenderer.on('player:show', () => fn()),
  onPlayerHidden: (fn) => ipcRenderer.on('player:hidden', () => fn()),
});
